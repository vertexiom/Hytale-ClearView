"""Generate x64 argument-preserving lazy forwarding stubs for the Windows API."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[2]
HOOKED={'wglGetProcAddress','wglSwapBuffers','wglDeleteContext'}

def generate(output):
    output.mkdir(parents=True,exist_ok=True)
    names=[s.strip() for s in (ROOT/'src/windows/exports.txt').read_text().splitlines() if s.strip() and not s.startswith('#')]
    assert len(names)==len(set(names)) and all(n.isidentifier() for n in names)
    forwarded=[n for n in names if n not in HOOKED]
    header=['/* Generated by tools/build/gen_windows_exports.py. */',f'#define CV_EXPORT_COUNT {len(forwarded)}',
            'static const char *cv_export_names[CV_EXPORT_COUNT]={']
    header += [f'    "{n}",' for n in forwarded]
    header += ['};','void *cv_export_targets[CV_EXPORT_COUNT];']
    (output/'exports_table.h').write_text('\n'.join(header)+'\n')
    # Windows x64 ABI: preserve 4 integer/pointer and 4 vector arguments, plus
    # caller stack arguments. 136 bytes aligns the stack and reserves shadow space.
    asm=['.text','.globl cv_forward_dispatch','.seh_proc cv_forward_dispatch','cv_forward_dispatch:',
         'subq $136, %rsp','.seh_stackalloc 136','.seh_endprologue',
         'movq %rcx, 32(%rsp)','movq %rdx, 40(%rsp)','movq %r8, 48(%rsp)','movq %r9, 56(%rsp)',
         'movdqu %xmm0, 64(%rsp)','movdqu %xmm1, 80(%rsp)','movdqu %xmm2, 96(%rsp)','movdqu %xmm3, 112(%rsp)',
         'movq %r10, 128(%rsp)','call cv_win_initialize',
         'movq 128(%rsp), %r10','leaq cv_export_targets(%rip), %r11','movq (%r11,%r10,8), %r11',
         'movq 32(%rsp), %rcx','movq 40(%rsp), %rdx','movq 48(%rsp), %r8','movq 56(%rsp), %r9',
         'movdqu 64(%rsp), %xmm0','movdqu 80(%rsp), %xmm1','movdqu 96(%rsp), %xmm2','movdqu 112(%rsp), %xmm3',
         'addq $136, %rsp','jmp *%r11','.seh_endproc']
    for i,name in enumerate(forwarded):
        asm += [f'.globl cv_export_{name}',f'cv_export_{name}:',f'movl ${i}, %r10d','jmp cv_forward_dispatch']
    (output/'exports.S').write_text('\n'.join(asm)+'\n')
    definition=['LIBRARY opengl32','EXPORTS']
    definition += [f'{n}=cv_export_{n}' if n not in HOOKED else f'{n}=cv_{n}' for n in names]
    (output/'opengl32.def').write_text('\n'.join(definition)+'\n')
    return len(names)

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('output',type=Path);args=p.parse_args()
    print('Generated',generate(args.output),'exports')
